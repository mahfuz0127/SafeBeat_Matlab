%% MATLAB Function code

processorChart.Script = sprintf([ ...
'function [filtered, envelope, peak, rr, bpm, sqi, label, confidence, accepted, diagnosis] = SafeBeatProcessor(ecg, Fs)\n' ...
'%%#codegen\n' ...
'%% SafeBeat streaming ECG processor\n' ...
'\n' ...
'persistent hpState lpState previousInput\n' ...
'persistent previousFiltered\n' ...
'persistent envelopeState\n' ...
'persistent previousEnvelope1 previousEnvelope2\n' ...
'persistent threshold signalLevel noiseLevel\n' ...
'persistent sampleCounter lastPeakSample refractoryCounter\n' ...
'persistent lastRR lastBPM\n' ...
'\n' ...
'if isempty(hpState)\n' ...
'    hpState = 0.0;\n' ...
'    lpState = 0.0;\n' ...
'    previousInput = 0.0;\n' ...
'    previousFiltered = 0.0;\n' ...
'    envelopeState = 0.0;\n' ...
'    previousEnvelope1 = 0.0;\n' ...
'    previousEnvelope2 = 0.0;\n' ...
'    threshold = 1e-6;\n' ...
'    signalLevel = 1e-5;\n' ...
'    noiseLevel = 1e-6;\n' ...
'    sampleCounter = 0.0;\n' ...
'    lastPeakSample = -1.0;\n' ...
'    refractoryCounter = 0.0;\n' ...
'    lastRR = 0.0;\n' ...
'    lastBPM = 0.0;\n' ...
'end\n' ...
'\n' ...
'%% Validate sampling frequency\n' ...
'if Fs < 1.0\n' ...
'    Fs = 360.0;\n' ...
'end\n' ...
'\n' ...
'sampleCounter = sampleCounter + 1.0;\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% ECG preprocessing\n' ...
'%% ----------------------------------------------------------\n' ...
'\n' ...
'%% High-pass filtering at approximately 0.5 Hz\n' ...
'hpAlpha = exp(-2.0*pi*0.5/Fs);\n' ...
'hpState = hpAlpha*(hpState + ecg - previousInput);\n' ...
'previousInput = ecg;\n' ...
'\n' ...
'%% Low-pass filtering at approximately 40 Hz\n' ...
'lpAlpha = exp(-2.0*pi*40.0/Fs);\n' ...
'lpState = lpAlpha*lpState + (1.0-lpAlpha)*hpState;\n' ...
'filtered = lpState;\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% QRS enhancement\n' ...
'%% ----------------------------------------------------------\n' ...
'\n' ...
'%% Derivative emphasizes the QRS slope\n' ...
'derivativeSignal = filtered - previousFiltered;\n' ...
'previousFiltered = filtered;\n' ...
'\n' ...
'%% Squaring\n' ...
'squaredSignal = derivativeSignal*derivativeSignal;\n' ...
'\n' ...
'%% Exponential approximation of an 80 ms moving integrator\n' ...
'envelopeAlpha = exp(-1.0/(0.080*Fs));\n' ...
'envelopeState = envelopeAlpha*envelopeState + ...\n' ...
'                (1.0-envelopeAlpha)*squaredSignal;\n' ...
'\n' ...
'envelope = envelopeState;\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% Adaptive R-peak detection\n' ...
'%% ----------------------------------------------------------\n' ...
'\n' ...
'peak = 0.0;\n' ...
'rr = lastRR;\n' ...
'bpm = lastBPM;\n' ...
'\n' ...
'if refractoryCounter > 0.0\n' ...
'    refractoryCounter = refractoryCounter - 1.0;\n' ...
'end\n' ...
'\n' ...
'isLocalMaximum = ...\n' ...
'    (previousEnvelope1 > previousEnvelope2) && ...\n' ...
'    (previousEnvelope1 >= envelope);\n' ...
'\n' ...
'if isLocalMaximum && ...\n' ...
'        previousEnvelope1 > threshold && ...\n' ...
'        refractoryCounter <= 0.0\n' ...
'\n' ...
'    peak = 1.0;\n' ...
'\n' ...
'    %% Refractory period of 200 milliseconds\n' ...
'    refractoryCounter = round(0.200*Fs);\n' ...
'\n' ...
'    if refractoryCounter < 1.0\n' ...
'        refractoryCounter = 1.0;\n' ...
'    end\n' ...
'\n' ...
'    if lastPeakSample > 0.0\n' ...
'        rrSamples = sampleCounter - 1.0 - lastPeakSample;\n' ...
'        candidateRR = rrSamples/Fs;\n' ...
'\n' ...
'        %% Physiological protection range: 24 to 240 BPM\n' ...
'        if candidateRR >= 0.25 && candidateRR <= 2.50\n' ...
'            lastRR = candidateRR;\n' ...
'            lastBPM = 60.0/candidateRR;\n' ...
'        end\n' ...
'    end\n' ...
'\n' ...
'    lastPeakSample = sampleCounter - 1.0;\n' ...
'\n' ...
'    signalLevel = 0.125*previousEnvelope1 + ...\n' ...
'                  0.875*signalLevel;\n' ...
'else\n' ...
'    if isLocalMaximum\n' ...
'        noiseLevel = 0.125*previousEnvelope1 + ...\n' ...
'                     0.875*noiseLevel;\n' ...
'    end\n' ...
'end\n' ...
'\n' ...
'rr = lastRR;\n' ...
'bpm = lastBPM;\n' ...
'\n' ...
'%% Adaptive Pan-Tompkins-style threshold\n' ...
'threshold = noiseLevel + 0.25*(signalLevel-noiseLevel);\n' ...
'\n' ...
'if threshold < 1e-10\n' ...
'    threshold = 1e-10;\n' ...
'end\n' ...
'\n' ...
'previousEnvelope2 = previousEnvelope1;\n' ...
'previousEnvelope1 = envelope;\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% Signal quality index\n' ...
'%% ----------------------------------------------------------\n' ...
'\n' ...
'qualityRatio = signalLevel/(signalLevel + noiseLevel + 1e-12);\n' ...
'\n' ...
'if qualityRatio < 0.0\n' ...
'    qualityRatio = 0.0;\n' ...
'elseif qualityRatio > 1.0\n' ...
'    qualityRatio = 1.0;\n' ...
'end\n' ...
'\n' ...
'sqi = qualityRatio;\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% Preliminary rhythm classification\n' ...
'%% ----------------------------------------------------------\n' ...
'%% Label 0: normal-rate rhythm\n' ...
'%% Label 1: abnormal-rate rhythm\n' ...
'%% Label 2: insufficient information\n' ...
'\n' ...
'if bpm <= 0.0\n' ...
'    label = 2.0;\n' ...
'elseif bpm >= 50.0 && bpm <= 100.0\n' ...
'    label = 0.0;\n' ...
'else\n' ...
'    label = 1.0;\n' ...
'end\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% Confidence estimation\n' ...
'%% ----------------------------------------------------------\n' ...
'\n' ...
'if label == 2.0\n' ...
'    confidence = 0.0;\n' ...
'elseif label == 0.0\n' ...
'    %% Confidence is high near the normal reference of 75 BPM\n' ...
'    rateDistance = abs(bpm-75.0)/75.0;\n' ...
'\n' ...
'    if rateDistance > 1.0\n' ...
'        rateDistance = 1.0;\n' ...
'    end\n' ...
'\n' ...
'    confidence = sqi*(1.0-rateDistance);\n' ...
'else\n' ...
'    %% Abnormal confidence increases with distance from normal range\n' ...
'    if bpm < 50.0\n' ...
'        abnormalDistance = (50.0-bpm)/50.0;\n' ...
'    else\n' ...
'        abnormalDistance = (bpm-100.0)/100.0;\n' ...
'    end\n' ...
'\n' ...
'    if abnormalDistance > 1.0\n' ...
'        abnormalDistance = 1.0;\n' ...
'    elseif abnormalDistance < 0.0\n' ...
'        abnormalDistance = 0.0;\n' ...
'    end\n' ...
'\n' ...
'    confidence = sqi*(0.60 + 0.40*abnormalDistance);\n' ...
'end\n' ...
'\n' ...
'if confidence < 0.0\n' ...
'    confidence = 0.0;\n' ...
'elseif confidence > 1.0\n' ...
'    confidence = 1.0;\n' ...
'end\n' ...
'\n' ...
'%% ----------------------------------------------------------\n' ...
'%% Confidence-based abstention\n' ...
'%% ----------------------------------------------------------\n' ...
'\n' ...
'if sqi >= 0.60 && ...\n' ...
'        confidence >= 0.50 && ...\n' ...
'        label ~= 2.0\n' ...
'\n' ...
'    accepted = 1.0;\n' ...
'    diagnosis = label;\n' ...
'else\n' ...
'    accepted = 0.0;\n' ...
'    diagnosis = 2.0;\n' ...
'end\n' ...
'\n' ...
'end\n']);

